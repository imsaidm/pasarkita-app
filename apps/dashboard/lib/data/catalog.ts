/**
 * Katalog dibaca dari PostgreSQL — tabel yang sama dengan kasir dan toko
 * online, jadi angka stok di ketiga aplikasi selalu satu.
 *
 * Medan yang belum punya sumber data tidak dikarang: foto kosong, rating dan
 * ulasan nol, harga coret tidak diisi. Medan Shopee diisi `unlinked` karena
 * integrasinya memang belum ada — menampilkan "synced" akan membuat pemilik
 * toko percaya barangnya sudah tayang di Shopee padahal tidak.
 */

const NO_STOCK_THRESHOLD_FALLBACK = 5;

function mapDbProduct(p: StorefrontProduct, threshold: number): AdminProduct {
  return {
    id: p.id,
    slug: p.slug,
    sku: p.sku,
    name: p.name,
    categorySlug: p.categorySlug,
    price: p.price,
    stock: p.stock,
    lowStockThreshold: threshold,
    status: "published",
    images: [...p.images],
    image: p.images[0] ?? "",
    rating: 0,
    reviewCount: 0,
    shortDescription: p.shortDescription,
    description: p.description,
    brand: "",
    condition: "BARU",
    weightGram: 0,
    dimensions: { lengthCm: 0, widthCm: 0, heightCm: 0 },
    variants: p.variants.map((v) => ({ name: v.name, options: [...v.options] })),
    variantMatrix: [
      {
        id: `${p.id}-def`,
        sku: p.sku,
        title: "Standar",
        price: p.price,
        stock: p.stock,
        shopeeSyncStatus: "unlinked",
      },
    ],
    channels: ["storefront"],
    shopeeCategoryId: "",
    shopeeCategoryName: "",
    shopeeItemId: "",
    shopeeSyncStatus: "unlinked",
    shopeeLastSyncedAt: "",
    updatedAtLabel: "",
  } as AdminProduct;
}

export async function getAllProducts(): Promise<AdminProduct[]> {
  const tenantId = await resolveTenantId();
  const rows = await listProducts(tenantId);
  return rows.map((p) => mapDbProduct(p, NO_STOCK_THRESHOLD_FALLBACK));
}

export async function getProductById(id: string): Promise<AdminProduct | null> {
  const all = await getAllProducts();
  return (
    all.find(
      (p) => p.id === id || p.slug === id || p.sku.toLowerCase() === id.toLowerCase(),
    ) ?? null
  );
}

export async function getProductBySlug(slug: string): Promise<AdminProduct | null> {
  const tenantId = await resolveTenantId();
  const found = await findProductBySlug(tenantId, slug);
  return found === null ? null : mapDbProduct(found, NO_STOCK_THRESHOLD_FALLBACK);
}

export async function getCategories(): Promise<Category[]> {
  return CATEGORIES;
}

export async function getCollections(): Promise<Collection[]> {
  return COLLECTIONS;
}

export async function getLowStockProducts(): Promise<AdminProduct[]> {
  const all = await getAllProducts();
  return all.filter((p) => p.stock <= p.lowStockThreshold && p.stock > 0);
}

export async function getOutOfStockProducts(): Promise<AdminProduct[]> {
  const all = await getAllProducts();
  return all.filter((p) => p.stock === 0);
}

export async function getShopeeSyncedProducts(): Promise<AdminProduct[]> {
  const all = await getAllProducts();
  return all.filter((p) => p.channels.includes("shopee"));
}
